-- Migração das conversas antigas (de_id/para_id) para conversas diretas.
INSERT INTO chat_conversas (tipo, chave, criado_por, atualizada_em)
  SELECT 'direta', 'dm:' || LEAST(de_id, para_id) || ':' || GREATEST(de_id, para_id), MIN(de_id), MAX(created_at)
  FROM chat_mensagens WHERE conversa_id IS NULL AND para_id IS NOT NULL GROUP BY LEAST(de_id, para_id), GREATEST(de_id, para_id)
  ON CONFLICT (chave) DO NOTHING;
UPDATE chat_mensagens m SET conversa_id = c.id FROM chat_conversas c
  WHERE m.conversa_id IS NULL AND m.para_id IS NOT NULL AND c.chave = 'dm:' || LEAST(m.de_id, m.para_id) || ':' || GREATEST(m.de_id, m.para_id);
INSERT INTO chat_membros (conversa_id, usuario_id)
  SELECT id, CAST(split_part(chave, ':', 2) AS integer) FROM chat_conversas WHERE tipo = 'direta'
  UNION SELECT id, CAST(split_part(chave, ':', 3) AS integer) FROM chat_conversas WHERE tipo = 'direta'
  ON CONFLICT DO NOTHING;
UPDATE chat_membros mb SET ultima_lida_id = COALESCE((SELECT MAX(m.id) FROM chat_mensagens m WHERE m.conversa_id = mb.conversa_id
  AND (m.de_id = mb.usuario_id OR m.lida_em IS NOT NULL)), 0) WHERE mb.ultima_lida_id IS NULL;


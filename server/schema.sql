-- Estoque por produto + embalagem (+ lote). Saldo = soma das movimentações (entrada positiva, saída negativa).
CREATE TABLE IF NOT EXISTS estoque_movimentos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id integer NOT NULL REFERENCES empresas(id),
  produto_id integer NOT NULL REFERENCES produtos(id),
  embalagem_id integer REFERENCES produto_embalagens(id),
  tipo text NOT NULL,                               -- entrada | saida | ajuste
  origem text NOT NULL DEFAULT 'manual',            -- compra | producao | venda | devolucao | cancelamento | inventario | perda | manual
  quantidade double precision NOT NULL,             -- com sinal: + entra, - sai
  lote text,
  validade text,
  custo_unitario double precision,
  fornecedor_id integer REFERENCES fornecedores(id),
  pedido_id integer REFERENCES pedidos(id),
  documento text,
  observacao text,
  usuario_id integer REFERENCES usuarios(id),
  created_at text NOT NULL DEFAULT sq_datetime('now', 'localtime')
);
CREATE INDEX IF NOT EXISTS idx_estoque_prod ON estoque_movimentos(empresa_id, produto_id, embalagem_id);

